    private fun integrationEnabled(): Boolean =
        System.getProperty("dshpm.integration") == "true" ||
            System.getenv("DASHPM_INTEGRATION") == "1"

    private fun loadToken(): String? {
        val home = System.getenv("HOME") ?: return null
        val envFile = Path.of(home, ".config", "voice-gateway", "env")
        if (!Files.isRegularFile(envFile)) return null
        return Files.readAllLines(envFile)
            .firstOrNull { it.startsWith("VOICE_GATEWAY_TOKEN=") }
            ?.substringAfter('=')?.trim()?.takeIf { it.isNotEmpty() }
    }

    /** 16 kHz mono s16 PCM, "移动端收到请回答。" (4.7 s, 37 632 samples). */
    private val speechPcm: ByteArray by lazy {
        Base64.getDecoder().decode(SPEECH_B64.filter { !it.isWhitespace() }.toByteArray())
    }

    @Test(timeout = 60_000L)
    fun realGatewaySpeechRoundRegistersDownlink() {
        assumeTrue("integration disabled — enable with DASHPM_INTEGRATION=1 or -Pintegration=true", integrationEnabled())
        val token = loadToken()
        assumeTrue("VOICE_GATEWAY_TOKEN not found in ~/.config/voice-gateway/env", token != null)

        val queued = CopyOnWriteArrayList<ByteArray>() // player-side receipt
        val player = object : PlayerSink {
            override fun enqueue(pcm: ByteArray) { queued.add(pcm) }
            override fun dropAll() {}
            override fun close() {}
        }
        val mic = object : MicSource {
            override fun start(onBlock: (ByteArray) -> Unit) {}
            override fun stop() {}
            override fun close() {}
        }
        val controller = VoiceController(
            sendPort = { },
            audioPort = { },
            mic = mic,
            player = player,
        )
        val client = VoiceGatewayClient(
            uri = URI("ws://127.0.0.1:8765/ws"),
            token = token!!,
            listener = controller,
            config = VoiceGatewayClient.Config(pingIntervalMillis = 60_000),
        )
        controller.rebindSendPort { client.send(it) }
        controller.rebindAudioPort { client.sendAudio(it) }
        controller.onChange = { /* phase-transition trace for diagnostics */
            it.phase?.let { ph -> println("[trace] phase=$ph detail=${it.transcript.lastOrNull()?.detail ?: ""}") }
        }
        try {
            client.connect()
            try {
                await("CONNECTED") { controller.state.connection == ConnectionState.CONNECTED }
            } catch (t: AssertionError) {
                // per-token ≤2: phone + PC tk online is the documented norm —
                // a busy gateway is an environment condition, not a regression
                assumeTrue(
                    "gateway slots busy (concurrent_limit): ${controller.state.error}",
                    !controller.state.error.orEmpty().contains("concurrent_limit"),
                )
                throw t
            }
            controller.wantsSession = true
            controller.activate()
            await("session LIVE") { controller.state.session == VoiceController.SessionState.LIVE }
            Thread.sleep(1_000) // head attach settle (python-probe parity)

            // stream the speech exactly as the mic path would: 800-sample blocks
            // coalesced to 200 ms sends, then 1 s of trailing silence so the
            // VAD endpointing closes the utterance
            val block = ChunkCoalescer.BLOCK_SAMPLES * 2
            var i = 0
            while (i < speechPcm.size) {
                controller.onMicBlock(speechPcm.copyOfRange(i, minOf(i + block, speechPcm.size)))
                i += block
                Thread.sleep(50)
            }
            repeat(20) { controller.onMicBlock(ByteArray(block)); Thread.sleep(50) }
            // wait for the head to answer: phases + downlink
            try {
                await("downlink binaries arrive (②c fork: frames DO reach the client)") {
                    controller.state.downlinkFrames > 0
                }
            } catch (t: AssertionError) {
                println(
                    "[diag] conn=${controller.state.connection} session=${controller.state.session} " +
                        "error=${controller.state.error} phases=${controller.state.transcript.map { it.phase }} " +
                        "upstream=${controller.state.upstreamBlocks}",
                )
                throw t
            }
            await("user_text transcript") {
                controller.state.transcript.any { it.phase == "user_text" }
            }
            await("assistant reply completes") {
                controller.state.transcript.any { it.phase == "assistant_end" }
            }
            // unmuted windows must have delivered audio to the player queue
            assertTrue(
                "queued ${queued.size} chunks / ${queued.sumOf { it.size }}B; " +
                    "arrived ${controller.state.downlinkFrames} frames / ${controller.state.downlinkBytes}B " +
                    "(mute-dropped ${controller.state.downlinkMuteDropped})",
                queued.sumOf { it.size } > 0,
            )
            println(
                "speech round: frames=${controller.state.downlinkFrames} bytes=${controller.state.downlinkBytes} " +
                    "muteDropped=${controller.state.downlinkMuteDropped} queuedBytes=${queued.sumOf { it.size }}",
            )
            controller.deactivate()
            await("session ended") { controller.state.session == VoiceController.SessionState.ENDED }
        } finally {
            client.close()
        }
    }

    private fun await(what: String, cond: () -> Boolean) {
        val deadline = System.nanoTime() + TimeUnit.SECONDS.toNanos(30)
        while (!cond() && System.nanoTime() < deadline) TimeUnit.MILLISECONDS.sleep(100)
        assertTrue("timeout waiting for $what", cond())
    }
